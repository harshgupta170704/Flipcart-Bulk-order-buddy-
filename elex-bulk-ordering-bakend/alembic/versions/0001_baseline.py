def _refuse_a_database_that_already_has_tables() -> None:
    """Stop before creating anything when the app's tables are already there.

    Without this the run would fail on the first CREATE TABLE with "already
    exists" — on SQLite, which commits each CREATE as it goes, possibly after
    making some tables — and nothing would say what to do instead.
    """
    if context.is_offline_mode():
        return  # --sql: there is no database to look at
    present = sorted(set(sa.inspect(op.get_bind()).get_table_names()) & set(TABLES))
    if present:
        raise CommandError(
            f"this database already holds the app's tables ({', '.join(present[:4])}"
            f"{', ...' if len(present) > 4 else ''}) but no Alembic revision: it was built by "
            "init_db or by a build older than Alembic. Do not run the baseline over it. Stamp it "
            "and upgrade instead: 'alembic stamp 0001', then 'alembic upgrade head', then "
            "'alembic check' (docs/DEPLOY.md section 5)."
        )


